// `npm run archive`: writes src/js/cloud-archive-data.js, the Cloud Archive's shelves, from this checkout's own git
// history (every commit reachable from HEAD). Refuses a shallow clone, so the archive is never a partial history.
// Days are UTC commit dates. A commit is credited to a GitHub login where the history itself says which: a
// `<id>+<login>@users.noreply.github.com` (or `<login>@users.noreply…`) address, or the `from <login>/…` of a PR merge;
// a name that ever committed under a login takes that login. Anyone else keeps the author name as the public history
// shows it. No email address is written out. See docs/cloud-archive/BUILD-PLAN.md.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });
if (git("rev-parse", "--is-shallow-repository").trim() !== "false") {
  console.error("cloud-archive: this clone is shallow; run `git fetch --unshallow` first so every commit is shelved.");
  process.exit(1);
}
const REPO = "OogaBoogaX/oogaboogaland";
const SEP = "\x1f", END = "\x1e";
const raw = git("log", "HEAD", "--date=unix", `--format=%H${SEP}%ct${SEP}%an${SEP}%ae${SEP}%P${SEP}%s${SEP}%b${END}`);
const commits = [];
for (const record of raw.split(END)) {
  const text = record.replace(/^\n/, "");
  if (!text) continue;
  const [sha, time, name, email, parents, subject, body] = text.split(SEP);
  const noreply = /^(?:\d+\+)?([A-Za-z0-9-]+(?:\[bot\])?)@users\.noreply\.github\.com$/i.exec(email);
  const merge = /^Merge pull request #(\d+) from ([A-Za-z0-9-]+)\//.exec(subject);
  const title = merge ? (body || "").split("\n").map((l) => l.trim()).find(Boolean) || subject : subject;
  commits.push({ sha, time: Number(time), name, login: noreply ? noreply[1] : null, prLogin: merge ? merge[2] : null,
    pr: merge ? Number(merge[1]) : 0, merge: parents.trim().split(" ").length > 1, title: title.trim(), bot: /\[bot\]$/i.test(name) || /\[bot\]/i.test(email) });
}
// A name that ever committed under a login is that login.
const nameLogin = new Map();
for (const c of commits) if (c.login && !nameLogin.has(c.name)) nameLogin.set(c.name, c.login);
const people = [], personIndex = new Map();
// Logins are case-insensitive: the first spelling seen stands for every other.
const person = (label) => {
  const key = label.toLowerCase();
  if (!personIndex.has(key)) { personIndex.set(key, people.length); people.push(label); }
  return personIndex.get(key);
};
const days = new Map();
// Oldest first, so a person's index follows when they first appeared.
for (const c of commits.sort((a, b) => a.time - b.time)) {
  // A PR merge credits the PR's author (its head's owner); a plain commit credits its author.
  const label = c.bot ? c.name : c.pr ? c.prLogin : c.login || nameLogin.get(c.name) || c.name;
  const day = new Date(c.time * 1000).toISOString().slice(0, 10);
  if (!days.has(day)) days.set(day, []);
  // [sha, person, title, pr, flags]: flags 1 bot, 2 merge.
  days.get(day).push([c.sha, person(label), c.title, c.pr, (c.bot ? 1 : 0) | (c.merge ? 2 : 0)]);
}
const head = git("rev-parse", "HEAD").trim();
const data = { repo: REPO, head, commits: commits.length, people, days: [...days].map(([date, list]) => ({ date, commits: list })) };
const out = `// Generated by \`npm run archive\` (scripts/cloud-archive.mjs) from the git history at ${head.slice(0, 12)}. Do not edit.
// The Cloud Archive's shelves: one day a shelf, one commit a book, as [sha, person, title, pr, flags (1 bot, 2 merge)].
(() => {
  "use strict";
  const BL = window.BL = window.BL || {};
  BL.cloudArchiveData = ${JSON.stringify(data)};
})();
`;
writeFileSync(new URL("../src/js/cloud-archive-data.js", import.meta.url), out);
console.log(`cloud-archive: ${commits.length} commits, ${days.size} days, ${people.length} people`);
